import glob,os,sys,xml.etree.ElementTree as ET
src=sys.argv[1]; out=sys.argv[2]
def lum(h):
    r,g,b=[int(h[i:i+2],16) for i in (0,2,4)]; return (0.299*r+0.587*g+0.114*b)/255
rows=[]
for f in sorted(glob.glob(os.path.join(src,"*.xml"))):
    name=os.path.basename(f)[:-4]
    if name=="Ruby Blue": continue          # every style is plain white in the asm/C lexers
    t=ET.parse(f).getroot()
    def lex(n):
        e=t.find(".//LexerType[@name='%s']"%n); d={}
        if e is not None:
            for w in e.findall("WordsStyle"): d[w.get("name")]=w.get("fgColor").upper()
        return d
    c,a=lex("c"),lex("asm")
    g={w.get("name"):w for w in t.findall(".//GlobalStyles/WidgetStyle")}
    d=g["Default Style"]; fg=d.get("fgColor").upper(); bg=d.get("bgColor").upper()
    cur=g["Current line background colour"].get("bgColor").upper()
    ln=g["Line number margin"].get("fgColor").upper()
    def pick(*cands):
        for x in cands:
            if x and x!=fg: return x
        return fg
    kw=pick(a.get("CPU INSTRUCTION"),c.get("INSTRUCTION WORD"))
    reg=pick(a.get("REGISTER"),c.get("TYPE WORD"))
    num=pick(a.get("NUMBER"),c.get("NUMBER"))
    mem=pick(c.get("OPERATOR"),a.get("OPERATOR"),num)
    lab=pick(a.get("IDENTIFIER"),c.get("PREPROCESSOR"))
    com=pick(a.get("COMMENT"),c.get("COMMENT"))
    sysc=pick(a.get("DIRECTIVE"),c.get("PREPROCESSOR"))
    io=pick(a.get("MATH INSTRUCTION"),a.get("EXT INSTRUCTION"),c.get("PREPROCESSOR"),c.get("TYPE WORD"))
    quo=pick(a.get("STRING"),c.get("STRING"))
    cols=[kw,reg,num,mem,lab,com,sysc,io,quo]
    rows.append((name,lum(bg)<0.5,bg,fg,cur,ln,cols))
with open(out,"w") as o:
    o.write("// Generated by tools/gen_npp_themes.py from Notepad++ (GPL-3) theme files in PowerEditor/installer/themes.\n")
    o.write("// Each theme keeps its original author/licence; see THIRD_PARTY.md.\n")
    o.write("#ifndef NPPTHEMES_H\n#define NPPTHEMES_H\n\nstruct NppTheme {\n    const char *name;\n    bool dark;\n    const char *bg, *fg, *currentLine, *lineNumber;\n    const char *syntax[9]; // keywords, registers, numbers, memory, labels, comments, system, iomacro, quotation\n};\n\n")
    o.write("static const NppTheme kNppThemes[] = {\n")
    for n,dk,bg,fg,cur,ln,cols in rows:
        o.write('    { "%s", %s, "#%s", "#%s", "#%s", "#%s", { %s } },\n'%(n,"true" if dk else "false",bg,fg,cur,ln,", ".join('"#%s"'%x for x in cols)))
    o.write("};\n\nstatic const int kNppThemeCount = sizeof(kNppThemes) / sizeof(kNppThemes[0]);\n\n#endif\n")
print(len(rows),"themes")
